function difficultyHint(mode: DifficultyMode): string {
  switch (mode) {
    case 'starter':
      return 'Все задания сложности 1 (стартовый уровень).'
    case 'basic':
      return 'Все задания сложности 2 (базовый уровень).'
    case 'advanced':
      return 'Все задания сложности 3 (повышенный уровень).'
    default:
      return 'Дифференцированная сложность: от 1 к 3 по ходу листа.'
  }
}

function contextPayload(draft: WorksheetDraft) {
  return {
    subject: draft.subject,
    grade: `${draft.grade} класс`,
    topic: draft.topic,
    teacher_wishes: draft.wishes?.trim().slice(0, WISHES_MAX_LENGTH) || null,
    task_count: draft.taskCount,
    difficulty_mode: draft.difficulty,
    difficulty_guidance: difficultyHint(draft.difficulty),
    add_intro: draft.addIntro,
    reference_file: referenceFilePayload(draft),
  }
}

function planPayload(draft: WorksheetDraft) {
  return draft.plan.map((p, i) => ({
    index: i + 1,
    type: p.taskType,
    type_label: labelForType(p.taskType),
    teacher_expectation: p.userExpectation?.trim() || null,
  }))
}

function blockBriefText(block: WorksheetBlock): string {
  if (block.type === 'fill_gaps') {
    return block.question || getGapsSourceText(block) || ''
  }
  return block.question || block.body || ''
}

function existingTasksBrief(blocks: WorksheetBlock[]) {
  return blocks
    .filter((b) => !['page_break', 'text', 'answer_field', 'table'].includes(b.type))
    .map((b, i) => ({
      index: i + 1,
      type: b.type,
      question: blockBriefText(b),
    }))
}

export function promptsForPlan(draft: WorksheetDraft) {
  const system = `Ты — методист школьного образования. Составь план рабочего листа: последовательность типов заданий и краткие ожидания учителя к каждому.

Доступные типы:
${TASK_TYPES_LIST}

${OUTPUT_FORMAT}

Верни JSON:
{
  "tasks": [
    { "type": "<код типа>", "expectation": "что именно отработать в этом задании (до 120 символов)" }
  ]
}

Требования к плану:
- Ровно ${draft.taskCount} элементов в tasks.
- Чередуй типы, не ставь подряд больше двух одинаковых.
- Логика: от простого к сложному / от узнавания к применению.
- Учитывай предмет, класс, тему и пожелания учителя.

${CONTEXT_USAGE_RULES}

${EXPECTATION_FIELD_RULES}

${CONTENT_RULES}`

  const user = JSON.stringify(contextPayload(draft), null, 2)
  return { system, user }
}

export function promptsForWorksheet(
  draft: WorksheetDraft,
  mode: 'create' | 'regenerate',
) {
  const modeBlock =
    mode === 'regenerate'
      ? `Режим: ПЕРЕГЕНЕРАЦИЯ. Создай НОВЫЕ задания по тому же плану и теме.
Не копируй формулировки из previous_tasks. Сохрани типы и педагогическую цель, замени содержание.`
      : `Режим: ПЕРВИЧНАЯ ГЕНЕРАЦИЯ рабочего листа по плану.`

  const system = `Ты — опытный методист и автор школьных рабочих листов.
${modeBlock}

${TASK_JSON_FIELDS}

${OUTPUT_FORMAT}

Верни JSON:
{
  "title": "краткое название листа",
  "intro": "1–2 предложения: общая информация по теме без местоимений, без «сегодня/вчера», без напутствий (или пустая строка, если intro не нужен)",
  "tasks": [ /* ровно столько, сколько в плане / task_count */ ]
}

${CONTENT_RULES}

Дополнительно по структуре листа:
- Строго соблюдай type из плана для каждого задания.
- Поле instruction у каждого задания — всегда "".
- Если в плане есть teacher_expectation — это методическая установка (инфинитив: «Сопоставить…», «Решить…»). Разверни её в формулировку question без служебных преамбул («Выбери правильный ответ…») и без местоимений; не копируй expectation дословно.
- Если add_intro=false — верни intro как "".
- question и options с дробями/выражениями — только LaTeX ($\\frac{a}{b}$, $\\cdot$). Не давай заданий вида «Вспомни правило… и запиши».
- order_items: дай перемешанный порядок; correct_answers — правильная последовательность.
- matching: right_items перемешай относительно left_items; в correct_answers укажи пары «лево → право».
- fill_gaps: question — короткая формулировка задания (1 предложение: что сделать). gaps_text — только текст с пропусками ___; не дублируй question и gaps_text. Правила и теорию не помещай в question — только в gaps_text, если они нужны как контекст перед строками с пропусками. Пропуски только в обычном тексте: не ставь ___ внутри формул ($...$), не используй \\text{___} и не делай gaps_answers из фрагментов формул. Формулы пиши целиком без пропусков; если нужно проверить знание формулы — вынеси пропуск в обычный текст рядом. Запрещено: gaps_text «(a+b)^2 = a^2 + ___ + b^2» с gaps_answers: ["2ab"] — вместо этого формула целиком, пропуск только в обычном тексте рядом.
- matching: question обязателен — ясно укажи, что нужно сопоставить (например, «Сопоставьте слова с значениями приставок»). Не оставляй question пустым.

${CONTEXT_USAGE_RULES}`

  const user = JSON.stringify(
    {
      ...contextPayload(draft),
      task_plan: planPayload(draft),
      previous_tasks: mode === 'regenerate' ? existingTasksBrief(draft.blocks) : undefined,
    },
    null,
    2,
  )

  return { system, user }
}

export function promptsForSingleTask(
  draft: WorksheetDraft,
  taskType: TaskType,
  expectation: string,
) {
  const system = `Ты — методист. Сгенерируй ОДНО школьное задание для рабочего листа.

Тип: ${taskType} (${labelForType(taskType)}).

${TASK_JSON_FIELDS}

${OUTPUT_FORMAT}

Верни JSON:
{ "task": { ...поля одного задания с type="${taskType}" } }

${CONTENT_RULES}

- Не повторяй формулировки из existing_tasks.
- Поле instruction — всегда "".
- Если есть teacher_expectation — это установка вида «Решить квадратное уравнение» / «Сопоставить…». Разверни в question без служебных преамбул и без местоимений; не копируй expectation дословно.
- fill_gaps: question — короткое задание; gaps_text — упражнение с пропусками, без дублирования question. Пропуски только в обычном тексте, не внутри формул ($...$). Запрещено: «(a+b)^2 = a^2 + ___ + b^2» с gaps_answers: ["2ab"].
- matching: question обязателен и понятен ученику.

${CONTEXT_USAGE_RULES}`

  const user = JSON.stringify(
    {
      ...contextPayload(draft),
      requested_type: taskType,
      teacher_expectation: expectation.trim() || null,
      existing_tasks: existingTasksBrief(draft.blocks),
    },
    null,
    2,
  )

  return { system, user }
}
